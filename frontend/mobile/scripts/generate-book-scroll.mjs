import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

// Hermes bytecode cannot provide executable Function#toString source at runtime.
const source = readFileSync(new URL("../src/lib/continuousBookScroll.ts", import.meta.url), "utf8");
const factory = source.slice(source.indexOf("export function createContinuousBookScroll"));
const compiled = ts.transpileModule(factory, {
  compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020, removeComments: true },
}).outputText.replace(/^export /u, "").trim();
const output = `// Generated by pnpm --filter @jojo/mobile generate:book-scroll.\nexport const CONTINUOUS_BOOK_SCROLL_FACTORY = ${JSON.stringify(`(${compiled})`)};\n`;
const target = new URL("../src/lib/continuousBookScroll.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== output) {
    throw new Error("Regenerate the native book scroll source with pnpm --filter @jojo/mobile generate:book-scroll");
  }
} else writeFileSync(target, output);
