import { readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";

// Ship source as a string: native production bundles cannot serialize JS functions.
const source = readFileSync(new URL("../src/speech-dom.ts", import.meta.url), "utf8");
const factory = source.slice(source.indexOf("export function createSpeechReader"), source.indexOf("export { SPEECH_EXCLUDED_ELEMENTS }"));
const compiled = ts.transpileModule(factory, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ES2020, removeComments: true } }).outputText.replace(/^export /u, "").trim();
const output = `// Generated by pnpm --filter @jojo/content generate:speech-reader.\nexport const SPEECH_READER_FACTORY = ${JSON.stringify(`(${compiled})`)};\n`;
const target = new URL("../src/speech-dom.generated.ts", import.meta.url);
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replaceAll("\r\n", "\n") !== output) throw new Error("Regenerate the native speech reader with pnpm --filter @jojo/content generate:speech-reader");
} else writeFileSync(target, output);
